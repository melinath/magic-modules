// KnownMissingDataSourceDocs lists the data sources in the beta provider that
// don't have a doc. This list should only shrink.
var KnownMissingDataSourceDocs = []string{
	"google_backup_dr_backup_plan",
	"google_storage_managed_folder_iam_policy",
}

// UnreadableDocsReport compares the fields that the missing doc detector can't
// find in resource docs with the fields it is known to be unable to find.
// Fields and data sources added by the change under review aren't included;
// DetectMissingDocs and DetectMissingDocsForDatasource report them.
type UnreadableDocsReport struct {
	// Fields the detector can't find that aren't in KnownUnreadableDocs, by
	// resource.
	NewUnreadableDocs map[string][]string
	// Fields in KnownUnreadableDocs that the detector can now find or that no
	// longer exist, by resource. These should be removed from
	// KnownUnreadableDocs.
	StaleUnreadableDocs map[string][]string
	// Data sources without a doc that aren't in KnownMissingDataSourceDocs.
	NewMissingDataSourceDocs []string
	// Data sources in KnownMissingDataSourceDocs that now have a doc or no
	// longer exist. These should be removed from KnownMissingDataSourceDocs.
	StaleMissingDataSourceDocs []string
}

// DetectUnreadableDocs checks the docs of resources and data sources against
// all of their fields and compares the result with the known unreadable docs.
//
// resources and dataSources are all of the provider's resources and data
// sources. inScope limits which of them are checked, along with the resources
// whose docs refer to their docs; a nil inScope checks all of them. Known entries for resources and data sources that no longer exist
// are always reported as stale. schemaDiff and dataSourceSchemaDiff are the
// change under review, whose new fields and data sources are skipped.
func DetectUnreadableDocs(resources, dataSources map[string]*schema.Resource, inScope func(name string) bool, schemaDiff, dataSourceSchemaDiff diff.SchemaDiff, repoPath string, knownDocs map[string][]string, knownDataSources []string) (UnreadableDocsReport, error) {
	if inScope == nil {
		inScope = func(string) bool { return true }
	}
	report := UnreadableDocsReport{
		NewUnreadableDocs:          make(map[string][]string),
		StaleUnreadableDocs:        make(map[string][]string),
		NewMissingDataSourceDocs:   []string{},
		StaleMissingDataSourceDocs: []string{},
	}

	checked := make(map[string]*schema.Resource)
	for name, resource := range resources {
		if inScope(name) || slices.ContainsFunc(resourceDocReferences[name], func(ref docReference) bool { return inScope(ref.Resource) }) {
			checked[name] = resource
		}
	}
	allFields := diff.ComputeSchemaDiff(nil, checked)
	for _, resource := range slices.Sorted(maps.Keys(checked)) {
		fieldsInDoc, _, err := documentedFields(resource, repoPath, 0)
		if err != nil {
			return report, err
		}
		known := listToMap(knownDocs[resource])
		fields := allFields[resource].FlattenedSchema.New
		for _, field := range slices.Sorted(maps.Keys(fields)) {
			if field == "condition" || strings.HasPrefix(field, "condition.") || fieldsInDoc[field] || known[field] {
				continue
			}
			if fieldDiff, ok := schemaDiff[resource].Fields[field]; ok && isNewField(fieldDiff) {
				continue
			}
			report.NewUnreadableDocs[resource] = append(report.NewUnreadableDocs[resource], field)
		}
		for _, field := range knownDocs[resource] {
			if _, ok := fields[field]; !ok || fieldsInDoc[field] {
				report.StaleUnreadableDocs[resource] = append(report.StaleUnreadableDocs[resource], field)
			}
		}
	}
	for resource, fields := range knownDocs {
		if _, ok := resources[resource]; !ok {
			report.StaleUnreadableDocs[resource] = slices.Clone(fields)
		}
	}

	knownDataSourceSet := listToMap(knownDataSources)
	for _, dataSource := range slices.Sorted(maps.Keys(dataSources)) {
		if !inScope(dataSource) {
			continue
		}
		_, err := dataSourceToDocFile(dataSource, repoPath)
		hasDoc := err == nil
		if knownDataSourceSet[dataSource] && hasDoc {
			report.StaleMissingDataSourceDocs = append(report.StaleMissingDataSourceDocs, dataSource)
		}
		if !knownDataSourceSet[dataSource] && !hasDoc && !isNewResource(dataSourceSchemaDiff[dataSource]) {
			report.NewMissingDataSourceDocs = append(report.NewMissingDataSourceDocs, dataSource)
		}
	}
	for _, dataSource := range knownDataSources {
		if _, ok := dataSources[dataSource]; !ok {
			report.StaleMissingDataSourceDocs = append(report.StaleMissingDataSourceDocs, dataSource)
		}
	}
	slices.Sort(report.StaleMissingDataSourceDocs)
	return report, nil
}

func isNewResource(resourceDiff diff.ResourceDiff) bool {
	return resourceDiff.ResourceConfig.Old == nil && resourceDiff.ResourceConfig.New != nil
}
