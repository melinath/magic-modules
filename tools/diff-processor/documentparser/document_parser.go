package documentparser

import (
	"regexp"
	"slices"
	"sort"
	"strings"
)

var (
	fieldNameRegex = regexp.MustCompile("[\\*|-]\\s+(?:<a\\s[^>]*>\\s*(?:</a>)?\\s*)?`([a-z0-9_\\./]+)`") // * `xxx`
	// An HTML anchor: <a name="xxx"> or <a id="xxx">
	anchorRegex = regexp.MustCompile(`(?m)^[ \t]*<a\s+(?:name|id)="([a-z0-9_-]+)"\s*>(?:\s*</a>)?`)
	// The heading of a nested block, optionally preceded by an anchor:
	// <a name="xxx"></a>The `xxx` block supports:
	blockHeaderRegex = regexp.MustCompile("(?m)^ ?(?:<a\\s+(?:name|id)=\"([a-z0-9_-]+)\"\\s*>\\s*(?:</a>)?\\s*)?The (?:[a-z, ]+ )?(`[^\\n]*):[ \\t]*$")
	// A block heading that wraps over up to three lines.
	wrappedBlockHeaderRegex = regexp.MustCompile("(?m)^ ?(?:<a\\s[^>]*>\\s*(?:</a>)?\\s*)?The\\b[^\\n]*\\n(?:[^\\n*\\s-][^\\n]*\\n){0,2}?[^\\n*\\s-][^\\n]*:[ \\t]*$")
	// A word in a block heading that shows that it starts a block.
	blockKeywordRegex = regexp.MustCompile(`\b(?:(?:sub)?blocks?|(?:sub)?list|supports?|contains|holds|includes)\b`)
	// A field name in a block heading.
	blockNameRegex = regexp.MustCompile("`([a-z0-9_.]+)(?:\\[\\])?`")
	// A link to an anchor in the same document: (#xxx)
	linkRegex = regexp.MustCompile(`\[([^\]]*)\]\(#([a-z0-9_-]+)\)`)
	// The text of a link to the documentation of a field's structure:
	// [documented below](#nested_xxx)
	structureLinkTextRegex = regexp.MustCompile(`(?i)\b(?:below|above)\b`)
	horizontalLineRegex    = regexp.MustCompile("- - -|-{3,}") // - - - or ---
	// An index in a field path written in the a.0.b format.
	indexRegex = regexp.MustCompile(`\.[0-9]+(\.|$)`)

	sectionSeparator = "## "
)

// How deeply nested blocks can link to further nested blocks.
const maxDepth = 20

// DocumentParser parses *.html.markdown resource doc files.
type DocumentParser struct {
	root *node
	// The text of the nested blocks, by the field names in their headings.
	blocksByName map[string][]string
	// The text of the nested blocks, by their anchors.
	blocksAnchors map[string][]string
	// The blocks that document a field that a bullet names.
	reached map[string]bool
	// The field names in the headings of the blocks with each anchor.
	anchorNames map[string][]string
}

type node struct {
	name     string
	children []*node
}

func NewParser() *DocumentParser {
	return &DocumentParser{
		blocksByName:  make(map[string][]string),
		blocksAnchors: make(map[string][]string),
		anchorNames:   make(map[string][]string),
		reached:       make(map[string]bool),
	}
}

func (d *DocumentParser) FlattenFields() []string {
	var paths []string
	traverse(&paths, "", d.root)
	// A field path such as `a.0.b` documents its parent fields.
	for _, path := range paths {
		for i := range path {
			if path[i] == '.' {
				paths = append(paths, path[:i])
			}
		}
	}
	sort.Strings(paths)
	return slices.Compact(paths)
}

func traverse(paths *[]string, path string, n *node) {
	if n == nil {
		return
	}
	var curPath string
	if path != "" {
		curPath = path + "." + n.name
	} else {
		curPath = n.name
	}
	if curPath != "" {
		*paths = append(*paths, curPath)
	}
	for _, c := range n.children {
		traverse(paths, curPath, c)
	}
}

// Parse parses a resource document markdown's argument and attribute sections.
// The format generated by mmv1/templates/terraform/resource.html.markdown.tmpl
// is fully supported, along with the common variations in handwritten docs.
func (d *DocumentParser) Parse(src []byte) error {
	text := strings.ReplaceAll(string(src), "\r\n", "\n")
	text = wrappedBlockHeaderRegex.ReplaceAllStringFunc(text, func(heading string) string {
		return strings.ReplaceAll(heading, "\n", " ")
	})
	var argument, attribute, ephemeralAttribute string
	for _, p := range strings.Split(text, "\n"+sectionSeparator) {
		if strings.HasPrefix(p, "Attributes Reference") {
			attribute = p
		}
		if strings.HasPrefix(p, "Argument Reference") {
			argument = p
		}
		if strings.HasPrefix(p, "Ephemeral Attributes Reference") {
			ephemeralAttribute = p
		}
	}
	var topLevel []string
	for _, section := range []string{argument, attribute, ephemeralAttribute} {
		if len(section) == 0 {
			continue
		}
		for _, part := range horizontalLineRegex.Split(section, -1) {
			topLevel = append(topLevel, d.extractBlocks(part))
		}
	}
	d.root = &node{}
	for _, t := range topLevel {
		d.root.children = append(d.root.children, d.buildNodes(t, "", 0, map[string]bool{})...)
	}
	// A block heading with a field path, such as "The `a.b` block supports:",
	// documents the field at that path even if its parent block doesn't list it.
	names := make([]string, 0, len(d.blocksByName))
	for name := range d.blocksByName {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		if !strings.Contains(name, ".") {
			continue
		}
		n := d.root
		for _, part := range strings.Split(name, ".") {
			var child *node
			for _, c := range n.children {
				if c.name == part {
					child = c
					break
				}
			}
			if child == nil {
				child = &node{name: part}
				n.children = append(n.children, child)
			}
			n = child
		}
		n.children = append(n.children, d.buildNodes(strings.Join(d.blocksByName[name], "\n"), name, 1, map[string]bool{})...)
	}
	// A block heading with a field name, such as "The `a` block supports:",
	// that no bullet leads to documents a top-level field.
	for _, name := range names {
		if strings.Contains(name, ".") || slices.ContainsFunc(d.blocksByName[name], func(block string) bool { return d.reached[block] }) {
			continue
		}
		var n *node
		for _, c := range d.root.children {
			if c.name == name {
				n = c
				break
			}
		}
		if n == nil {
			n = &node{name: name}
			d.root.children = append(d.root.children, n)
		}
		n.children = append(n.children, d.buildNodes(strings.Join(d.blocksByName[name], "\n"), name, 1, map[string]bool{})...)
	}
	return nil
}

type blockStart struct {
	pos    int
	anchor string
	names  []string
}

// Record the nested blocks in the text and return the text before the first block.
func (d *DocumentParser) extractBlocks(text string) string {
	var starts []blockStart
	covered := map[int]bool{}
	for _, m := range blockHeaderRegex.FindAllStringSubmatchIndex(text, -1) {
		if !blockKeywordRegex.MatchString(text[m[4]:m[5]]) {
			continue
		}
		s := blockStart{pos: m[0]}
		if m[2] >= 0 {
			s.anchor = text[m[2]:m[3]]
		}
		for _, n := range blockNameRegex.FindAllStringSubmatch(text[m[4]:m[5]], -1) {
			s.names = append(s.names, n[1])
		}
		if len(s.names) == 0 && s.anchor == "" {
			continue
		}
		covered[m[0]] = true
		starts = append(starts, s)
	}
	for _, m := range anchorRegex.FindAllStringSubmatchIndex(text, -1) {
		if covered[m[0]] {
			continue
		}
		starts = append(starts, blockStart{pos: m[0], anchor: text[m[2]:m[3]]})
	}
	if len(starts) == 0 {
		return text
	}
	sort.Slice(starts, func(i, j int) bool { return starts[i].pos < starts[j].pos })
	for i, s := range starts {
		end := len(text)
		if i+1 < len(starts) {
			end = starts[i+1].pos
		}
		block := text[s.pos:end]
		if s.anchor != "" {
			d.blocksAnchors[s.anchor] = append(d.blocksAnchors[s.anchor], block)
			for _, name := range s.names {
				d.anchorNames[s.anchor] = append(d.anchorNames[s.anchor], normalize(name))
			}
		}
		for _, name := range s.names {
			name = normalize(name)
			d.blocksByName[name] = append(d.blocksByName[name], block)
		}
	}
	return text[:starts[0].pos]
}

func normalize(name string) string {
	for indexRegex.MatchString(name) {
		name = indexRegex.ReplaceAllString(name, "$1")
	}
	return strings.TrimSuffix(name, ".")
}

func (d *DocumentParser) buildNodes(text, path string, depth int, visited map[string]bool) []*node {
	if depth > maxDepth {
		return nil
	}
	var nodes []*node
	parts := splitWithRegexp(text, fieldNameRegex)
	for _, p := range parts[1:] {
		fieldName := findPattern(p, fieldNameRegex)
		if fieldName == "" {
			continue
		}
		name := normalize(fieldName)
		if path != "" {
			name = strings.TrimPrefix(name, path+".")
		}
		n := &node{name: name}
		fullPath := name
		if path != "" {
			fullPath = path + "." + name
		}
		blocks := d.findBlocks(p, fullPath)
		for _, block := range blocks {
			d.reached[block] = true
		}
		key := strings.Join(blocks, "\n")
		if len(blocks) > 0 && !visited[key] {
			v := map[string]bool{key: true}
			for k := range visited {
				v[k] = true
			}
			n.children = append(n.children, d.buildNodes(key, fullPath, depth+1, v)...)
		}
		nodes = append(nodes, n)
	}
	return nodes
}

// Find the nested blocks that document the children of a field.
func (d *DocumentParser) findBlocks(text, fullPath string) []string {
	// Prefer a link to a block whose heading names the field, then a link that
	// says the structure is documented elsewhere, such as
	// "[documented below](#nested_xxx)", rather than a link in the field's
	// description to a block that documents another field.
	links := linkRegex.FindAllStringSubmatch(text, -1)
	for _, m := range links {
		if blocks, ok := d.blocksAnchors[m[2]]; ok && namesMatch(d.anchorNames[m[2]], fullPath) {
			return blocks
		}
	}
	for _, m := range links {
		if blocks, ok := d.blocksAnchors[m[2]]; ok && structureLinkTextRegex.MatchString(m[1]) {
			return blocks
		}
	}
	// Fall back to blocks titled with the field's name, preferring the longest
	// match with the field's path.
	parts := strings.Split(fullPath, ".")
	for i := range parts {
		key := strings.Join(parts[i:], ".")
		if blocks, ok := d.blocksByName[key]; ok {
			return blocks
		}
	}
	return nil
}

// Whether a block whose heading names the given fields documents the field at
// fullPath.
func namesMatch(names []string, fullPath string) bool {
	for _, name := range names {
		if fullPath == name || strings.HasSuffix(fullPath, "."+name) {
			return true
		}
	}
	return false
}

func findPattern(text string, re *regexp.Regexp) string {
	match := re.FindStringSubmatch(text)
	if match != nil {
		return match[1]
	}
	return ""
}

func splitWithRegexp(text string, re *regexp.Regexp) []string {
	matches := re.FindAllStringIndex(text, -1)
	if len(matches) == 0 {
		return []string{text}
	}
	var parts []string
	start := 0
	for _, match := range matches {
		end := match[0]

		parts = append(parts, text[start:end])
		start = end
	}
	parts = append(parts, text[start:])
	return parts
}
